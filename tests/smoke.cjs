// Run with Playwright available: node tests/smoke.cjs
const {chromium}=require('playwright');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.resolve('index.html')).href);
 await page.locator('[data-enemy="report"]').click();
 await page.locator('[data-enemy="calendar"]').click();
 await page.locator('[data-enemy="slime"]').click();
 await page.locator('#overlay-start').click();
 assert.equal(await page.evaluate(()=>actors.filter(a=>a.team===1).every(a=>['report','calendar'].includes(a.skinId)&&a.image.startsWith('data:image/svg+xml'))),true);
 await page.waitForTimeout(1600);
 assert.equal(await page.locator('#overlay').isVisible(),false);
 await page.locator('#pause').click();
 assert.equal(await page.locator('#run-state').textContent(),'일시정지');
 await page.locator('#pause').click();
 await page.locator('[data-mode="jump"]').click();
 await page.locator('#overlay-start').click();
 await page.locator('#game').press('Space');
 await page.waitForTimeout(300);
 assert.equal(await page.evaluate(()=>actors[0].grounded),false);
 await page.locator('[data-mode="battle"]').click();
 await page.locator('#overlay-start').click();
 await page.waitForTimeout(500);
 assert.equal(await page.evaluate(()=>actors.length),3);
 await page.locator('#manual').click();
 await page.waitForFunction(()=>turnState.phase==='waiting'&&turnState.currentId===actors[0].id);
 const before=await page.evaluate(()=>actors[0].energy||0);
 await page.locator('#game').press('Space');
 await page.waitForFunction(previous=>(actors[0].energy||0)>previous,before);
 assert.equal(await page.locator('#turn-banner').isVisible(),true);
 await page.locator('#restart').click();
 await page.locator('[data-mode="dungeon"]').click();
 await page.screenshot({path:'preview.png',fullPage:true});
 await page.setViewportSize({width:680,height:750});
 await page.locator('#compact').click();
 assert.equal(await page.locator('.sidebar').isVisible(),false);
 assert.equal(await page.locator('.widget-toolbar').evaluate(el=>getComputedStyle(el).backgroundColor),'rgba(0, 0, 0, 0)');
 const widths=await page.evaluate(()=>[document.querySelector('.widget-toolbar').getBoundingClientRect().width,document.getElementById('game').getBoundingClientRect().width]);
 assert.equal(widths[0],widths[1]);
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('.sidebar').isVisible(),true);
 const svg=Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32"><rect width="32" height="32" fill="red"/></svg>');
 await page.locator('#enemy-upload').setInputFiles({name:'테스트 악당.svg',mimeType:'image/svg+xml',buffer:svg});
 await page.waitForFunction(()=>enemyRoster.some(a=>a.name==='테스트 악당'));
 await page.evaluate(()=>{enemySelected=[enemyRoster.find(a=>a.name==='테스트 악당').id];start();});
 assert.equal(await page.evaluate(()=>actors.filter(a=>a.team===1).every(a=>a.name==='테스트 악당')),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: three modes, jump input, manual turn command, pause, compact mode; no page errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
